@dataclass(frozen=True)
class Category:
    """One category of M1 §7.2: the op its cases run, how many cases it needs at least, what it covers, and the
    builder of its case inputs (``None``: M1-T5b writes them)."""

    name: str
    op: str
    minimum: int
    covers: str
    inputs: Callable[[], list[dict[str, Any]]] | None = None


def _rng_vector(rng: XorShift32, lo: float, hi: float, n: int) -> list[float]:
    return [round(lo + (hi - lo) * rng.uniform(), 6) for _ in range(n)]


def _degenerate(a: list[float], b: list[float]) -> bool:
    """``|a × b| <= 1e-8·|a||b|`` (M1 §7.2: such bases are not Gauss cases)."""
    a3, b3 = np.array(a + [0.0] * (3 - len(a))), np.array(b + [0.0] * (3 - len(b)))
    return float(np.linalg.norm(np.cross(a3, b3))) <= 1e-8 * float(np.linalg.norm(a3) * np.linalg.norm(b3))


def points_inputs() -> list[dict[str, Any]]:
    """The matrices of M1 §7.1 "格点": diagonals (the repeat order), shears, the det-16 BN matrix of Materials
    Studio, the surface matrices, and a det < 0 one (the same points as −P)."""
    mats = {
        "diag-2-2-2": [[2, 0, 0], [0, 2, 0], [0, 0, 2]], "diag-3-1-2": [[3, 0, 0], [0, 1, 0], [0, 0, 2]],
        "identity": [[1, 0, 0], [0, 1, 0], [0, 0, 1]], "shear-37": [[1, 0, 0], [0, 1, 0], [37, 0, 1]],
        "ms-bn-det-16": [[-3, 1, 1], [-1, -1, 3], [1, 1, 1]], "sqrt3": [[2, 1, 0], [-1, 1, 0], [0, 0, 1]],
        "c2x2": [[1, 1, 0], [-1, 1, 0], [0, 0, 1]], "3sqrt3": [[6, 3, 0], [-3, 3, 0], [0, 0, 1]],
        "det-minus-2": [[0, 1, 0], [1, 0, 0], [0, 0, 2]],
    }
    return [{"id": f"m1-points-{k}", "args": {"matrix": m}} for k, m in mats.items()]


def gauss_inputs() -> list[dict[str, Any]]:
    """At least 500 non-degenerate bases × the three ``angle`` values (M1 §7.2): random 3D pairs, long thin 2D bases
    (a reduced pair times a random unimodular matrix) and the exact ties of the hexagonal, square, rectangular and
    centred meshes.  Inputs are rounded to 6 decimals, so both languages read the same numbers."""
    rng = XorShift32(7201)
    bases: list[tuple[list[float], list[float]]] = []
    while len(bases) < 380:
        a, b = _rng_vector(rng, -4, 4, 3), _rng_vector(rng, -4, 4, 3)
        if not _degenerate(a, b):
            bases.append((a, b))
    while len(bases) < 520:
        u, v = np.array(_rng_vector(rng, -3, 3, 2)), np.array(_rng_vector(rng, -3, 3, 2))
        p, q = int(rng.next_u32() % 25) - 12, int(rng.next_u32() % 25) - 12
        a2, b2 = (u + p * v).round(6).tolist(), ((p * q + 1) * v + q * u).round(6).tolist()  # det [[1, p], [q, pq+1]] = 1
        if not _degenerate(a2, b2):
            bases.append((a2, b2))
    s3 = round(math.sqrt(3), 12)
    ties = [([2.7719, 0], [-1.38595, 1.38595 * s3]), ([2.7719, 0], [1.38595, 1.38595 * s3]),
            ([1.38595, 1.38595 * s3], [2.7719, 0]), ([2.556, 0], [0, 2.556]), ([2.7719, 0], [0, 3.92]),
            ([2.4820, 0], [-0.827333, 2.339994]), ([3, 0], [1.5, 4]), ([3, 0], [-1.5, 4]), ([1, 0, 0], [0, 0, 7])]
    bases += [(list(map(float, a)), list(map(float, b))) for a, b in ties]
    return [{"id": f"m1-gauss-{k:04d}-{tag}", "args": {"a": a, "b": b, "angle": angle}}
            for k, (a, b) in enumerate(bases) for angle, tag in (("obtuse", "obtuse"), ("acute", "acute"), (None, "none"))]


def niggli_inputs() -> list[dict[str, Any]]:
    """At least 180 cells (M1 §7.2): random right-handed cells (lengths 2–8 Å, angles 60–120°) times random
    unimodular matrices of det +1 (sums of rows), rounded to 6 decimals, non-degenerate."""
    rng = XorShift32(9311)
    cells = []
    while len(cells) < 200:
        la, lb, lc = (2 + 6 * rng.uniform() for _ in range(3))
        al, be, ga = (math.radians(60 + 60 * rng.uniform()) for _ in range(3))
        cx = math.cos(be)
        cy = (math.cos(al) - math.cos(be) * math.cos(ga)) / math.sin(ga)
        cz2 = 1 - cx * cx - cy * cy
        if cz2 < 0.05:
            continue
        cell = np.array([[la, 0, 0], [lb * math.cos(ga), lb * math.sin(ga), 0], [lc * cx, lc * cy, lc * math.sqrt(cz2)]])
        m = np.eye(3, dtype=int)
        for _ in range(4):
            i, j = int(rng.next_u32() % 3), int(rng.next_u32() % 3)
            if i != j:
                m[i] += (int(rng.next_u32() % 5) - 2) * m[j]
        out = (m @ cell).round(6)
        if abs(np.linalg.det(out)) > 1e-3 * np.prod(np.linalg.norm(out, axis=1)):
            cells.append(out.tolist())
    return [{"id": f"m1-niggli-{k:03d}", "args": {"cell": c}} for k, c in enumerate(cells)]


