def _xorshift_case(cid: str, note: str, *, keys: tuple[str, ...] = ("value", "uniform", "noise"),
                   **args: Any) -> dict[str, Any]:
    """An ``xorshift32`` case comparing the results *keys* exactly (``tol`` 0)."""
    from tests.ops.m1 import xorshift32_op
    result = xorshift32_op(None, dict(args))  # type: ignore[arg-type]
    expect = {k: result[k] for k in keys if k in result}
    return {"id": cid, "op": "xorshift32", "args": args, "expect": expect, "tol": {k: 0 for k in expect},
            "note": note}


def _digest_case(cid: str, name: str, args: dict[str, Any], note: str, *, full: bool) -> dict[str, Any]:
    """A ``structureDigest`` case of the recipe *name*: atoms and digests always; with *full* also every atom."""
    s = build(name, args)
    d = s.to_dict(decimals=12)
    st: dict[str, Any] = {"name": s.name, "pbc": [True, True, True]}
    if full:
        st.update({"symbols": d["symbols"], "cell": d["cell"], "positions": d["positions"],
                   "props": {k: d.get("props", {}).get(k) for k in ("tags", "selective_dynamics")}})
        if s.info:
            st["info"] = s.info
    else:
        st["cell"] = d["cell"]
    case = {"id": cid, "op": "structureDigest", "input": recipe_input(name, **args),
            "expect": {"structure": st, "atoms": len(s), "digest": structure_digest(s)}, "note": note}
    if full:
        case["tol"] = {"positions": 1e-10, "cell": 1e-10}
    else:
        case["tol"] = {"cell": 1e-10}
    return case


def _error_case(cid: str, error: str, op: str = "buildRecipe", **args: Any) -> dict[str, Any]:
    """An argument error, checked by running the op in Python now: the message must be the expected one."""
    from tests.ops.m1 import build_recipe_op, xorshift32_op
    fn = {"buildRecipe": build_recipe_op, "xorshift32": xorshift32_op}[op]
    try:
        fn(None, dict(args))  # type: ignore[arg-type]
    except ValueError as exc:
        assert error in str(exc), (cid, str(exc), error)
    else:
        raise AssertionError(f"{cid}: no error")
    return {"id": cid, "op": op, "args": args, "expect": {"error": error}}


