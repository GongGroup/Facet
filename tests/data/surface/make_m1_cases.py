#: Category name → function(case stub) → the case's ``expect`` (and ``tol``, ``skip``) from the Python M1.
#: Filled in by M1-T5b; a category without an entry keeps m1_cases.json from being written.
EXPECTATIONS: dict[str, Callable[[dict[str, Any]], dict[str, Any]]] = {}


def m1_cases() -> tuple[list[dict[str, Any]] | None, list[str]]:
    """The cases of m1_cases.json, or ``None`` and the categories that still lack inputs or expectations."""
    pending = [c.name for c in CATEGORIES if c.inputs is None or c.name not in EXPECTATIONS]
    if pending:
        return None, pending
    cases = []
    for cat in CATEGORIES:
        stubs = cat.inputs()  # type: ignore[misc]
        if len(stubs) < cat.minimum:
            raise AssertionError(f"{cat.name}: {len(stubs)} cases, M1 §7.2 asks for at least {cat.minimum}")
        for stub in stubs:
            case = {"id": stub["id"], "op": stub.get("op", cat.op), **{k: stub[k] for k in ("args", "input") if k in stub}}
            case.update(EXPECTATIONS[cat.name](stub))
            cases.append(case)
    return cases, []


# ======================================================================== writing
def file_text(rel: str, cases: list[dict[str, Any]]) -> str:
    lines = ["{", f'  "schema": {json.dumps(SCHEMA)},',
             f'  "description": {json.dumps(DESCRIPTIONS[rel], ensure_ascii=False)},', '  "cases": [']
    body = [json.dumps({k: c[k] for k in KEY_ORDER if k in c}, ensure_ascii=False, separators=(", ", ": "))
            for c in cases]
    lines += ["    " + b + ("," if i < len(body) - 1 else "") for i, b in enumerate(body)]
    lines += ["  ]", "}"]
    return "\n".join(lines) + "\n"


def list_categories() -> None:
    for cat in CATEGORIES:
        n = f"{len(cat.inputs())} inputs" if cat.inputs else "inputs: M1-T5b"
        exp = "expectations: yes" if cat.name in EXPECTATIONS else "expectations: M1-T5b"
        need = f", at least {cat.minimum}" if cat.minimum else ""
        print(f"{cat.name:26s} op {cat.op:24s} {n}{need}; {exp}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the files on disk instead of writing")
    ap.add_argument("--list", action="store_true", help="list the categories of m1_cases.json and exit")
    opts = ap.parse_args(argv)
    if opts.list:
        list_categories()
        return 0
    check_neighbour_shells()
    check_contcar_geometry()
    check_recipe_semantics()
    files = {RECIPE_CHECK: file_text(RECIPE_CHECK, recipe_check_cases())}
    cases, pending = m1_cases()
    if cases is not None:
        files[M1_CASES] = file_text(M1_CASES, cases)
    else:
        print(f"note: {M1_CASES} not written: inputs or expectations pending (M1-T5b) for {', '.join(pending)}")
    stale = []
    for rel, text in files.items():
        path = HERE / rel
        if opts.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.write_text(text, encoding="utf-8")
    if opts.check:
        if stale:
            print("out of date: " + ", ".join(stale))
            return 1
        print(f"{len(files)} file{'s' if len(files) > 1 else ''} up to date")
        return 0
    n = sum(text.count('"id": ') for text in files.values())
    print(f"wrote {', '.join(sorted(files))} ({n} cases) under {HERE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
