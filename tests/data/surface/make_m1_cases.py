# ================================================================================================ helpers
def recipe_input(recipe: str, /, **args: Any) -> dict[str, Any]:
    """A case input that builds the recipe *recipe* from *args*."""
    return {"recipe": {"name": recipe, "args": args}}


def pt111(**extra: Any) -> dict[str, Any]:
    """The arguments of a Pt(111) slab (a = 3.92 Å, acceptance §0.4) with a 15 Å vacuum, updated by *extra*."""
    return {"element": "Pt", "a": 3.92, "layers": 4, "vacuum": 15, **extra}


def build(name: str, args: dict[str, Any]) -> Structure:
    """The recipe's structure (through the same function the registered recipe calls)."""
    return slab(name, args)


# ======================================================================= independent checks of the recipes
def _min_image_shell(s: Structure, centre: int, images: int = 2) -> list[float]:
    """Sorted distances from atom *centre* to every other atom and image (in-plane images up to ±*images*, and the
    images along c)."""
    cell = np.asarray(s.cell, dtype=float)
    pos = np.asarray(s.positions, dtype=float)
    out = []
    for i in range(-images, images + 1):
        for j in range(-images, images + 1):
            for k in (-1, 0, 1):
                shift = i * cell[0] + j * cell[1] + k * cell[2]
                d = np.linalg.norm(pos + shift - pos[centre], axis=1)
                out.extend(float(x) for x in d if x > 1e-9)
    return sorted(out)


def check_neighbour_shells() -> None:
    """Every face is a piece of its bulk: an atom of the middle layer has the bulk's first neighbour shell.

    fcc: 12 at a/√2; hcp: 6 at √(a²/3 + c²/4) in the layers above and below and 6 at a in its own layer; bcc: 8 at
    a√3/2; graphene: 3 at a/√3.  (fcc(110) needs the layers k ± 2, so the slabs have 7 layers.)
    """
    a_fcc, a_bcc, a_hcp, c_hcp, a_gr = 3.92, 2.866, 2.71, 4.28, 2.46
    inter = math.sqrt(a_hcp ** 2 / 3 + c_hcp ** 2 / 4)
    expected = {
        "fcc111": ({"element": "Pt", "a": a_fcc}, [(a_fcc / math.sqrt(2), 12)]),
        "fcc100": ({"element": "Cu", "a": a_fcc}, [(a_fcc / math.sqrt(2), 12)]),
        "fcc110": ({"element": "Pt", "a": a_fcc}, [(a_fcc / math.sqrt(2), 12)]),
        "hcp0001": ({"element": "Ru", "a": a_hcp, "c": c_hcp}, [(inter, 6), (a_hcp, 6)]),
        "bcc110": ({"element": "Fe", "a": a_bcc}, [(a_bcc * math.sqrt(3) / 2, 8)]),
        "graphene": ({"element": "C", "a": a_gr}, [(a_gr / math.sqrt(3), 3)]),
    }
    for face, (args, shells) in expected.items():
        for gamma in ((120, 60) if FACES[face].hexagonal else (None,)):
            full = {**args, "vacuum": 12, **({"layers": 7} if FACES[face].layered else {}),
                    **({"gamma": gamma} if gamma else {})}
            s = build(face, full)
            centre = len(s) // 2 if FACES[face].layered else 0
            dist = _min_image_shell(s, centre)
            k = 0
            for r, n in shells:
                got = dist[k:k + n]
                assert len(got) == n and all(abs(x - r) < 1e-9 for x in got), (face, gamma, r, n, got[:n + 1])
                k += n
            assert dist[k] > shells[-1][0] + 1e-3, (face, gamma, "shell too large", dist[k])


def check_contcar_geometry() -> None:
    """``fcc111`` Pt p(3×3) 4L with 15 Å is the CONTCAR fixture: the same cell and the same atoms (the fixture lists
    them in another order, and VASP wrapped two bottom atoms to f_c = 0.99999, 2.2e-4 Å below the top of the cell)."""
    fixture = parse_text((HERE / "contcar_pt111.vasp").read_text(encoding="utf-8"), filename="CONTCAR")
    s = build("fcc111", pt111(supercell=[3, 3]))
    cell = np.asarray(s.cell)
    assert np.abs(cell - np.asarray(fixture.cell)).max() < 1e-12, (cell, fixture.cell)
    inv = np.linalg.inv(cell)
    frac_fix = np.asarray(fixture.positions) @ inv
    used = set()
    for p in np.asarray(s.positions):
        d = (frac_fix - p @ inv + 0.5) % 1.0 - 0.5           # minimum image in fractional coordinates
        dist = np.linalg.norm(d @ cell, axis=1)
        j = int(np.argmin(dist))
        wrapped = frac_fix[j, 2] > 0.9999
        assert dist[j] < (3e-4 if wrapped else 1e-9) and j not in used, (p, j, dist[j])
        used.add(j)
    assert len(used) == len(fixture) == 36


def check_recipe_semantics() -> None:
    """The other facts the cases freeze: the generator's anchor, the noise, the deletions and the props."""
    assert xorshift32_step(MARSAGLIA_STATE) == MARSAGLIA_FIRST
    assert XorShift32(state=MARSAGLIA_STATE).take(1) == [MARSAGLIA_FIRST]
    # noise: σ·√3·(2u − 1) is bounded by σ√3 and has a standard deviation close to σ
    noise = noise_values(0.005, XorShift32(11).take(30000))
    assert np.abs(noise).max() < 0.005 * S3 and abs(noise.mean()) < 1e-4 and abs(noise.std() - 0.005) < 1e-4
    big = pt111(layers=25, supercell=[20, 20], noise={"sigma": 0.005, "seed": 11})
    full, cut = build("fcc111", big), build("fcc111", {**big, "delete": "top:25"})
    ideal = build("fcc111", {k: v for k, v in big.items() if k != "noise"})
    assert len(full) == 10000 and len(cut) == 9975 and cut.name == "Pt(111) p(20×20) 25L"
    shift = np.asarray(full.positions) - np.asarray(ideal.positions)
    assert np.abs(shift).max() < 0.005 * S3                    # every atom moved by the noise, within σ√3
    assert np.array_equal(np.asarray(cut.positions), np.asarray(full.positions)[:9975])  # deleted after the noise
    top = np.asarray(ideal.positions)[-400:, 2]
    assert np.all(top == top.max()) and top.max() > np.asarray(ideal.positions)[:-400, 2].max()  # the top layer is last
    # σ = 0 leaves the atoms alone; tags count from the top of each copy; fix fixes the bottom layers of each copy
    zero = build("fcc111", pt111(noise={"sigma": 0, "seed": 3}))
    assert structure_digest(zero) == structure_digest(build("fcc111", pt111()))
    double = build("fcc111", pt111(supercell=[1, 1, 2], tags=True, fix=1))
    assert double.props["tags"] == [4, 3, 2, 1] * 2
    assert [f[0] for f in double.props["selective_dynamics"]] == [False, True, True, True] * 2


