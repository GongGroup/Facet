#!/usr/bin/env python3
"""Write the web builder's copy of the crystal reference tables, crystallume/web/js/build/reference.js.

    python scripts/gen_reference_data.py            # write the file
    python scripts/gen_reference_data.py --check    # exit 1 when the file is out of date

The default and tabulated lattice parameters of the crystal prototypes have one home, the Python builder
crystallume/build/crystal.py (PROTOTYPES and the tables _REF_A, _REF_C, _REF_AB and _FALLBACK_PARAMS).
This script copies them into reference.js, which the web builder (crystallume/web/js/build/crystal.js) reads,
so that both build the same structures. Run it after changing a table and commit both files:
tests/test_build.py fails while reference.js is out of date. Nothing runs this script at run time.
"""

# Sources of the values set when the two builders were aligned (crystallume/build/crystal.py):
#
# Lattice constants at room temperature (Å): Cu 3.615, bcc Fe 2.866, bcc Cr 2.884, hcp Mg a = 3.209 and
# c = 5.211, alpha-Po (simple cubic) 3.359; hexagonal BN a = 2.504 (bulk h-BN, Pease, Acta Cryst. 5, 356 (1952)).
#
# Wurtzite internal parameter u (anions at (1/3, 2/3, u)); other compounds get the ideal value 3/8:
#   ZnO 0.382          diffraction, Kisi & Elcombe, Acta Cryst. C45, 1867 (1989)
#   GaN 0.377          X-ray diffraction, Schulz & Thiemann, Solid State Commun. 23, 815 (1977)
#   AlN 0.382          same paper
#   InN 0.377          not measured; the LDA value of Bernardini, Fiorentini & Vanderbilt, Phys. Rev. B 56, R10024 (1997)
#   CdS 0.377          experimental value quoted by Xu & Ching, Phys. Rev. B 48, 4335 (1993)
#   ZnS 0.375          2H polytype, Kisi & Elcombe (1989)
#
# MX2 thickness: the height between the two chalcogen layers of one layer, h = (3/2 - 2z) c in the bulk 2H
# structure (P6_3/mmc, X at (1/3, 2/3, z)); other compounds get MoS2's 3.17 Å:
#   MoS2 3.17          c = 12.295 Å, z = 0.621: Bronsema, de Boer & Jellinek, Z. anorg. allg. Chem. 540, 15 (1986)
#   MoSe2 3.34         c = 12.927 Å, z = 0.6210: same paper
#   WS2 3.14           Schutte, de Boer & Jellinek, J. Solid State Chem. 70, 207 (1987)
#   WSe2 3.34          same paper (W-Se 2.526 Å, Se-Se 3.34 Å)
#   MoTe2 3.60         c = 13.964 Å, z = 0.621: Puotinen & Newnham, Acta Cryst. 14, 691 (1961)

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "crystallume" / "web" / "js" / "build" / "reference.js"

#: The keys of crystal.PROTOTYPES that the web builder reads.
PROTOTYPE_KEYS = ("defaultElements", "defaultA", "defaultC", "params", "spacegroup", "spacegroupNumber", "is2D")

HEADER = """\
// Reference tables of the crystal builder, written by scripts/gen_reference_data.py from
// crystallume/build/crystal.py, which holds the only copy: do not edit this file. After changing a table there,
// run `python scripts/gen_reference_data.py` and commit both files (tests/test_build.py checks that they agree).
// crystal.js reads these tables; referenceParameters() and buildCrystal() apply the rules of the Python builder.
"""


def _builder() -> Any:
    """The module ``crystallume.build.crystal`` of this checkout (the package exports a function of that name)."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    return importlib.import_module("crystallume.build.crystal")


def _js(value: Any) -> str:
    """*value* as a JavaScript literal (JSON: numbers with the shortest round-trip digits, as JS parses them)."""
    return json.dumps(value, ensure_ascii=False, allow_nan=False)


def render() -> str:
    """The text of ``reference.js`` for the tables in ``crystallume/build/crystal.py``."""
    m = _builder()
    out = [HEADER]
    out.append("/** The built-in prototypes: example elements and their parameters (Å; Python PROTOTYPES). */")
    out.append("export const PROTOTYPES = {")
    for pid, meta in m.PROTOTYPES.items():
        out.append(f"  {_js(pid)}: {_js({k: meta[k] for k in PROTOTYPE_KEYS})},")
    out.append("};\n")
    out.append("/** Experimental a (Å) of one-element crystals, by prototype and element (Python _REF_A). */")
    out.append("export const REF_A = {")
    for pid, table in m._REF_A.items():
        out.append(f"  {_js(pid)}: {_js(table)},")
    out.append("};\n")
    out.append("/** Experimental c (Å) of the one-element crystals of REF_A that have a c axis (Python _REF_C). */")
    out.append("export const REF_C = {")
    for pid, table in m._REF_C.items():
        out.append(f"  {_js(pid)}: {_js(table)},")
    out.append("};\n")
    out.append("/**")
    out.append(" * Compounds by prototype, keyed by the elements in role order joined with spaces (Python _REF_AB).")
    out.append(" * c is null for cubic cells and 2D prototypes (their default cell height); params holds the prototype")
    out.append(" * parameters that depend on the compound (wurtzite u, MX2 thickness in Å).")
    out.append(" */")
    out.append("export const REF_COMPOUNDS = {")
    for pid, table in m._REF_AB.items():
        out.append(f"  {_js(pid)}: {{")
        for els, (a, c, params) in table.items():
            out.append(f"    {_js(' '.join(els))}: {_js({'a': a, 'c': c, 'params': params})},")
        out.append("  },")
    out.append("};\n")
    out.append("/** Prototype parameters of compounds that REF_COMPOUNDS does not list (Python _FALLBACK_PARAMS). */")
    out.append(f"export const FALLBACK_PARAMS = {_js(m._FALLBACK_PARAMS)};")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write crystallume/web/js/build/reference.js from crystallume/build/crystal.py.")
    ap.add_argument("--check", action="store_true", help="only check that the file is up to date (exit 1 if not)")
    args = ap.parse_args(argv)
    text = render()
    rel = TARGET.relative_to(ROOT).as_posix()
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
    if args.check:
        if current != text:
            print(f"{rel} is out of date: run python scripts/gen_reference_data.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date")
        return 0
    if current == text:
        print(f"{rel} is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
